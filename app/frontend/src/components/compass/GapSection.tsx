import type { CompassJob, GapAssessment, GapBatchResult, GapEvidence, GapJobResult, QualificationStatus } from "../../types";
import { gapKey, type GapBatch } from "../../state/useGapBatch";

const STATUS_LABEL: Record<QualificationStatus, string> = {
  supported: "Supported by your profile",
  unknown: "Not shown in your profile",
  explicit_gap: "Conflicts with your profile",
};
const STATUS_ICON: Record<QualificationStatus, string> = { supported: "✓", unknown: "?", explicit_gap: "✕" };
const KIND_LABEL = { required: "Required", preferred: "Preferred", unclear: "Mentioned" } as const;

interface Props {
  /** The jobs sent to the Compass (picks only, reposts already merged). */
  picks: CompassJob[];
  gap: GapBatch;
  snapshotReady: boolean;
}

/** AI skills gap analysis for every job in the Compass: one request, results grouped per job, each point citing its lines. */
export default function GapSection({ picks, gap, snapshotReady }: Props) {
  const ids = picks.map((p) => p.job.id);
  const key = gapKey(ids);
  const { state, consent, setConsent } = gap;
  const mine = state.status !== "idle" && state.key === key ? state : null;
  const busy = mine?.status === "loading";

  return (
    <div className="cp-card ga">
      <header className="cp-cardhead">
        <div>
          <h2>Skills gap analysis for each job</h2>
          <p className="cp-sub">
            An AI model reads all {picks.length} jobs at once and compares each one's requirements with your profile, showing the exact lines it relied on.
            A requirement your profile does not mention is “not shown in your profile”, which is different from “you don't have it”. It is not a hiring or eligibility judgment.
          </p>
        </div>
      </header>

      {!(mine?.status === "done") && (
        <>
          <p>
            <label>
              <input type="checkbox" checked={consent} onChange={(e) => setConsent(e.target.checked)} />{" "}
              I agree to send my profile's experience and skills (not my name, email, phone or links) and the descriptions of these {picks.length} jobs to OpenAI,
              in one request. The result is kept in your demo session, so running it again for the same jobs is free.
            </label>
          </p>
          <p>
            <button type="button" className="btn btn--primary btn--sm" disabled={!consent || busy || !snapshotReady} onClick={() => void gap.run(ids)}>
              {busy ? "Analysing…" : `Analyse these ${picks.length} jobs`}
            </button>
            {busy && <span className="cp-sub"> This can take a minute or two for a long list.</span>}
          </p>
        </>
      )}

      {mine?.status === "unavailable" && (
        <p className="notice" role="alert">The AI skills gap analysis is turned off on this server, so nothing was sent. Ask whoever runs the demo to start it without the -NoAI option.</p>
      )}
      {mine?.status === "error" && <p className="field__error" role="alert">{mine.message}</p>}
      {mine?.status === "done" && <Results picks={picks} result={mine.result} onAgain={gap.clear} />}
    </div>
  );
}

function Results({ picks, result, onAgain }: { picks: CompassJob[]; result: Extract<GapBatchResult, { state: "completed" }>; onAgain: () => void }) {
  const totals = { supported: 0, unknown: 0, explicit_gap: 0 } as Record<QualificationStatus, number>;
  let shown = 0;
  picks.forEach((p) => {
    const r = result.jobs[p.job.id];
    if (r?.state === "completed") {
      shown += 1;
      r.assessment.qualifications.forEach((q) => { totals[q.status] += 1; });
    }
  });
  const total = totals.supported + totals.unknown + totals.explicit_gap;

  return (
    <div className="ga__result">
      <p className="ga__summary" role="status">
        {shown} of {picks.length} jobs analysed, {total} requirements read: <strong>{totals.supported}</strong> supported by your profile,{" "}
        <strong>{totals.unknown}</strong> not shown in your profile, <strong>{totals.explicit_gap}</strong> conflicting.
        {result.failed > 0 && ` ${result.failed} ${result.failed === 1 ? "job" : "jobs"} could not be checked and ${result.failed === 1 ? "is" : "are"} marked below; running it again retries them.`}
      </p>

      <ul className="ga__jobs">
        {picks.map((p) => (
          <JobBlock key={p.job.id} pick={p} result={result.jobs[p.job.id]} candidateEvidence={result.candidateEvidence} />
        ))}
      </ul>

      <p className="cp-sub">Generated by an AI model from the lines shown. Check each point against your own history and the full listing.</p>
      <p><button type="button" className="btn btn--sm" onClick={onAgain}>Run again</button></p>
    </div>
  );
}

function JobBlock({ pick, result, candidateEvidence }: { pick: CompassJob; result: GapJobResult | undefined; candidateEvidence: GapEvidence[] }) {
  const title = `${pick.job.title} · ${pick.job.company.name}`;
  if (!result || result.state === "failed") {
    return <li className="ga__job"><p className="ga__jobtitle">{title}</p><p className="notice notice--compact">{result?.reason ?? "No result for this job."}</p></li>;
  }
  const a = result.assessment;
  if (a.evidence_sufficiency === "insufficient") {
    return <li className="ga__job"><p className="ga__jobtitle">{title}</p><p className="notice notice--compact">Not enough to assess: {a.insufficiency_reason ?? "the profile or the listing is too sparse."}</p></li>;
  }
  const counts = { supported: 0, unknown: 0, explicit_gap: 0 } as Record<QualificationStatus, number>;
  a.qualifications.forEach((q) => { counts[q.status] += 1; });
  return (
    <li className="ga__job">
      <details>
        <summary>
          <span className="ga__jobtitle">{title}</span>
          <span className="ga__counts">
            <span className="ga__status ga__status--supported">✓ {counts.supported}</span>
            <span className="ga__status ga__status--unknown">? {counts.unknown}</span>
            <span className="ga__status ga__status--explicit_gap">✕ {counts.explicit_gap}</span>
          </span>
        </summary>
        <JobDetail assessment={a} candidateEvidence={candidateEvidence} />
      </details>
    </li>
  );
}

function JobDetail({ assessment: a, candidateEvidence }: { assessment: GapAssessment; candidateEvidence: GapEvidence[] }) {
  const text = (id: string) => candidateEvidence.find((e) => e.evidence_id === id)?.text ?? a.evidence_catalog.find((e) => e.evidence_id === id)?.text ?? null;
  const quotes = (ids: string[], who: string) =>
    ids.map(text).filter((t): t is string => Boolean(t)).map((t, i) => <blockquote key={`${who}${i}`} className="ga__quote"><span>{who}</span>{t}</blockquote>);
  return (
    <div className="ga__body">
      <h4>Requirements</h4>
      <ul className="ga__list">
        {a.qualifications.map((q) => (
          <li key={q.qualification_id} className={`ga__item ga__item--${q.status}`}>
            <div className="ga__head">
              <span className={`ga__status ga__status--${q.status}`}><span aria-hidden="true">{STATUS_ICON[q.status]}</span> {STATUS_LABEL[q.status]}</span>
              <span className="ga__kind">{KIND_LABEL[q.classification]}</span>
            </div>
            <p className="ga__req">{q.qualification}</p>
            <p className="ga__why">{q.rationale}</p>
            {quotes(q.candidate_evidence_ids, "Your profile")}
            {quotes(q.job_evidence_ids, "The listing")}
          </li>
        ))}
      </ul>
      {a.transferable_experience.length > 0 && (
        <>
          <h4>Experience that may carry over</h4>
          <ul className="ga__list">
            {a.transferable_experience.map((t, i) => (
              <li key={i} className="ga__item">
                <p className="ga__req">{t.job_duty}</p>
                <p className="ga__why">{t.rationale}</p>
                {quotes(t.candidate_evidence_ids, "Your profile")}
                {quotes(t.job_evidence_ids, "The listing")}
              </li>
            ))}
          </ul>
        </>
      )}
      {a.next_steps.length > 0 && (
        <>
          <h4>Next steps</h4>
          <ul className="ga__steps">{a.next_steps.map((s, i) => <li key={i}>{s.action}</li>)}</ul>
        </>
      )}
    </div>
  );
}
